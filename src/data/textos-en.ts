export function spellTextEn(c: SpellCard): string {
  switch (c.sp) {
    case 'dmg': return `${c.v} damage to an enemy creature that was already in play.`;
    case 'buff': return `+${c.a}/+${c.h} to one of your creatures that was already in play.`;
    case 'lane': return `Choose an enemy row: ${c.v} damage to every creature in it.`;
    case 'shield': return 'Gives Shield to one of your creatures that was already in play.';
    case 'poison': return 'Poisons an enemy creature that was already in play.';
    case 'face': return `${c.v} direct damage to the enemy hero.`;
    case 'heal': return `Heal your hero for ${c.v}.`;
    case 'draw': return `Draw ${c.v} cards.`;
  }
}

